from abc import ABC


class BankingSystem(ABC):
    """
    Interface for a simple banking system. Do not edit this file.
    Implement every method in `BankingSystemImpl` (banking_system_impl.py).
    """

    def create_account(self, timestamp: int, account_id: str) -> bool:
        """
        Create a new account with a balance of 0.
        Return True if it was created, False if `account_id` already exists.
        """
        return False

    def deposit(self, timestamp: int, account_id: str, amount: int) -> int | None:
        """
        Deposit `amount` into `account_id`.
        Return the new balance, or None if the account doesn't exist.
        """
        return None

    def transfer(
        self,
        timestamp: int,
        source_account_id: str,
        target_account_id: str,
        amount: int,
    ) -> int | None:
        """
        Move `amount` from `source_account_id` to `target_account_id`.
        Return the source balance after the transfer, or None if either account
        doesn't exist, both are the same account, or the source has too little money.
        """
        return None
