from abc import ABC


class InMemoryDB(ABC):
    """
    Interface for a simple in-memory database. Do not edit this file.
    Implement every method in `InMemoryDBImpl` (in_memory_db_impl.py).
    """

    def set(self, key: str, field: str, value: str) -> None:
        """
        Set `field` in the record `key` to `value`, creating the record if needed
        and replacing any existing value.
        """
        return None

    def get(self, key: str, field: str) -> str | None:
        """
        Return the value of `field` in the record `key`, or None if the record or
        field doesn't exist.
        """
        return None

    def delete(self, key: str, field: str) -> bool:
        """
        Remove `field` from the record `key`.
        Return True if it was removed, False if the record or field doesn't exist.
        """
        return False

    def scan(self, key: str) -> list[str]:
        """
        Return every field of the record `key` as "<field>(<value>)", sorted by
        field name. Return [] if the record doesn't exist.
        """
        return []

    def scan_by_prefix(self, key: str, prefix: str) -> list[str]:
        """
        Like `scan`, but only fields whose name starts with `prefix`.
        """
        return []
