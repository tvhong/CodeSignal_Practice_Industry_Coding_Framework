from abc import ABC


class InMemoryDB(ABC):
    """
    Interface for a simple in-memory database. Do not edit this file.
    Implement every method in `InMemoryDBImpl` (in_memory_db_impl.py).
    """

    def set(self, key: str, field: str, value: str) -> None:
        """
        Set `field` in the record `key` to `value`, creating the record if needed
        and replacing any existing value.
        """
        return None

    def get(self, key: str, field: str) -> str | None:
        """
        Return the value of `field` in the record `key`, or None if the record or
        field doesn't exist.
        """
        return None

    def delete(self, key: str, field: str) -> bool:
        """
        Remove `field` from the record `key`.
        Return True if it was removed, False if the record or field doesn't exist.
        """
        return False

    def scan(self, key: str) -> list[str]:
        """
        Return every field of the record `key` as "<field>(<value>)", sorted by
        field name. Return [] if the record doesn't exist.
        """
        return []

    def scan_by_prefix(self, key: str, prefix: str) -> list[str]:
        """
        Like `scan`, but only fields whose name starts with `prefix`.
        """
        return []

    def set_at(self, timestamp: int, key: str, field: str, value: str) -> None:
        """
        Like `set`. The field never expires, and any existing TTL is removed.
        """
        return None

    def set_at_with_ttl(self, timestamp: int, key: str, field: str, value: str, ttl: int) -> None:
        """
        Like `set_at`, but the field is visible only until `timestamp + ttl`
        (exclusive).
        """
        return None

    def delete_at(self, timestamp: int, key: str, field: str) -> bool:
        """
        Like `delete`. Return False if the field has expired.
        """
        return False

    def get_at(self, timestamp: int, key: str, field: str) -> str | None:
        """
        Like `get`. Return None if the field has expired.
        """
        return None

    def scan_at(self, timestamp: int, key: str) -> list[str]:
        """
        Like `scan`, but only fields visible at `timestamp`.
        """
        return []

    def scan_by_prefix_at(self, timestamp: int, key: str, prefix: str) -> list[str]:
        """
        Like `scan_by_prefix`, but only fields visible at `timestamp`.
        """
        return []

    def backup(self, timestamp: int) -> int:
        """
        Save the visible fields and their remaining TTLs.
        Return the number of records with at least one visible field.
        """
        return 0

    def restore(self, timestamp: int, timestamp_to_restore: int) -> None:
        """
        Replace the database with the latest backup taken at or before
        `timestamp_to_restore`. Remaining TTLs restart from `timestamp`.
        """
        return None
